import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const root=dirname(fileURLToPath(import.meta.url));
if(!process.argv[2])throw Error('Usage: node build.mjs path/to/StudyDesk.html');
const base=readFileSync(process.argv[2],'utf8');
if(!base.includes('id="app"')||base.includes('id="study-updater"'))throw Error('Use a standalone StudyDesk build without the hosted updater.');
const updater=readFileSync(join(root,'update.js'),'utf8');
const html=base.replace('</body>',`<script id="study-updater">${updater}</script>\n</body>`);
const version=createHash('sha256').update(html).digest('hex').slice(0,12);
writeFileSync(join(root,'index.html'),html);
writeFileSync(join(root,'sw.js'),`const PREFIX='studydesk-'+new URL(self.registration.scope).pathname+'-';
const CACHE=PREFIX+'${version}';
const SHELL=new URL('./index.html',self.location).href;
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.add(new Request(SHELL,{cache:'reload'})))));
self.addEventListener('message',event=>{if(event.data==='ACTIVATE')self.skipWaiting();});
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith(PREFIX)&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{if(event.request.method==='GET'&&event.request.mode==='navigate'&&new URL(event.request.url).origin===self.location.origin)event.respondWith(caches.open(CACHE).then(cache=>cache.match(SHELL)).then(response=>response||fetch(event.request)));});
`);
console.log('Built hosted release '+version);
